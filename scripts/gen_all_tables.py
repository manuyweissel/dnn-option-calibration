def generate_ablation_table(data: dict, output_dir: Path) -> None:
    print("\n[Ablation Table]")

    rows = []

    def _safe_pct(a: float | None, b: float | None) -> str:
        if a is None or b is None or b == 0:
            return NA
        return f"{abs((b - a) / b) * 100:.0f}\\%"

    # A1: Greeks supervision
    nn = data.get("bs_nn_baseline.json", {})
    nnm2 = data.get("bs_nnm2.json", {})
    g_nn = nn.get("mean", {}).get("mae_gamma")
    g_nnm2 = nnm2.get("mean", {}).get("mae_gamma")
    rows.append([
        "Greek supervision (A1)",
        r"$\mathrm{MAE}_\Gamma$ $\downarrow$",
        _safe_pct(g_nnm2, g_nn),
        "NN vs NN-M2; tests H1",
    ])

    # A2: Activation smoothness
    sp = data.get("act_ablation_bs.json", data.get("bs_softplus_full.json", {}))
    rl = data.get("act_ablation_relu.json", {})
    g_sp = sp.get("mean", {}).get("mae_gamma")
    g_rl = rl.get("mean", {}).get("mae_gamma")
    rows.append([
        "Smooth activation (A2)",
        r"$\mathrm{MAE}_\Gamma$ $\downarrow$",
        _safe_pct(g_sp, g_rl),
        "Softplus vs ReLU; tests H2",
    ])

    r_sp = sp.get("mean", {}).get("rmse_price")
    r_rl = rl.get("mean", {}).get("rmse_price")
    rows.append([
        "Smooth activation (A2)",
        r"Price RMSE $\downarrow$",
        _safe_pct(r_sp, r_rl),
        "Softplus vs ReLU",
    ])

    # A3: Grid density
    sparse = data.get("lv_density_10x5.json", {})
    dense = data.get("lv_density_50x20.json", {})
    e_sp = sparse.get("mean", {}).get("rmse_extrap")
    e_dn = dense.get("mean", {}).get("rmse_extrap")
    rows.append([
        "Grid density (A3)",
        r"Extrap.\ RMSE $\downarrow$",
        _safe_pct(e_dn, e_sp),
        "Dense vs sparse; tests H3",
    ])
    p_sp = sparse.get("mean", {}).get("param_rel_err")
    p_dn = dense.get("mean", {}).get("param_rel_err")
    rows.append([
        "Grid density (A3)",
        r"$e_\psi$ $\downarrow$",
        _safe_pct(p_dn, p_sp),
        "Dense vs sparse; tests H3",
    ])

    tex = _latex_table(
        "tab:ablation-summary",
        ["Ablation", "Metric", "Effect size", "Notes"],
        rows,
    )
    (output_dir / "table10_4.tex").write_text(tex, encoding="utf-8")
    print(f"  -> table10_4.tex")


# Method families for pooling measured inference latency (per-seed medians
# are pooled over every experiment belonging to the family).
COMPLEXITY_FAMILIES = {
    "NN": ["bs_nn_baseline.json", "lv_nn_baseline.json", "heston_nn_baseline.json"],
    "NN-PDE": ["bs_nnpde.json", "lv_nnpde.json"],
    "NN-M2": ["bs_nnm2.json", "lv_nnm2.json", "heston_nnm2.json"],
    "PINN": ["bs_softplus_full.json", "lv_dnn.json"],
}


def _pooled_seed_values(data: dict, keys: list[str], metric: str) -> list[float]:
    """Collect per-seed values of ``metric`` across the given experiments."""
    vals = []
    for key in keys:
        for m in data.get(key, {}).get("all_metrics", []):
            v = m.get(metric)
            if v is not None:
                vals.append(float(v))
    return vals


def _median(vals: list[float]) -> float | None:
    if not vals:
        return None
    s = sorted(vals)
    n = len(s)
    mid = n // 2
    return s[mid] if n % 2 else 0.5 * (s[mid - 1] + s[mid])


def _fmt_latency_ms(ms: float | None) -> str:
    if ms is None:
        return NA
    if ms < 1.0:
        return f"${ms:.2f}$\\,ms"
    if ms < 100.0:
        return f"${ms:.1f}$\\,ms"
    return f"${ms / 1000.0:.2f}$\\,s"


def _fmt_duration(ms: float) -> str:
    """Format one duration in its natural unit (ms / s / min)."""
    unit = "ms" if ms < 1000 else ("s" if ms < 120000 else "min")
    v = ms / {"ms": 1.0, "s": 1000.0, "min": 60000.0}[unit]
    num = f"{v:.0f}" if v >= 10 else f"{v:.2g}"
    return f"${num}$\\,{unit}"


def _fmt_duration_range(ms_values: list[float]) -> str:
    """Format a min--max calibration wall-clock range, per-endpoint units.

    The classical ranges span orders of magnitude (40 ms BS calibration up to
    ~40 min Heston), so each endpoint gets its own natural unit.
    """
    if not ms_values:
        return NA
    lo, hi = min(ms_values), max(ms_values)
    if lo == hi:
        return f"calib.\\ {_fmt_duration(lo)}"
    return f"calib.\\ {_fmt_duration(lo)}--{_fmt_duration(hi)}"


def generate_complexity_table(data: dict, output_dir: Path) -> None:
    """Structural complexity table (thesis table7_1.tex) with measured timing.

    Neural 'Inference' cells are pooled per-seed medians of
    ``inference_latency_ms`` (forward pass over the held-out test grid,
    60 points under the default split).
    Classical cells are measured calibration wall-clock ranges (``duration_ms``
    mean per model) — a different quantity, labelled 'calib.' explicitly.
    """
    print("\n[Complexity Table] measured inference/calibration timing")

    static = {
        # method: (parameters, memory, models)
        "PINN": ("${\\sim}$13k", "Moderate", "BS, LV"),
        "NN-PDE": ("${\\sim}$13k", "Moderate", "BS, LV"),
        "NN-M2": ("${\\sim}$13k", "Low--Moderate", "BS, LV, Heston"),
        "NN": ("${\\sim}$13k", "Low", "BS, LV, Heston"),
    }

    rows = []
    for method in ("PINN", "NN-PDE", "NN-M2", "NN"):
        params, memory, models = static[method]
        # Measured per-epoch wall-clock time: median over all seeds of the
        # family (pooled over the models listed), same pooling as the latency.
        epoch_ms = _median(
            _pooled_seed_values(data, COMPLEXITY_FAMILIES[method], "epoch_time_ms")
        )
        lat = _median(
            _pooled_seed_values(data, COMPLEXITY_FAMILIES[method], "inference_latency_ms")
        )
        rows.append([method, params, _fmt_latency_ms(epoch_ms), _fmt_latency_ms(lat), memory, models])

    det_ms = [
        v for k in ("classical_bs", "classical_lv", "classical_heston")
        if (v := _get(data, k, "duration_ms")) is not None
    ]
    mc_ms = [
        v for k in ("classical_mc_bs", "classical_mc_lv", "classical_mc_heston")
        if (v := _get(data, k, "duration_ms")) is not None
    ]
    rows.append([
        "Classical (det.)", "$\\sim$1--5", "---",
        _fmt_duration_range(det_ms), "Low", "BS, LV, Heston",
    ])
    rows.append([
        "Classical (MC)", "$\\sim$1--5", "---",
        _fmt_duration_range(mc_ms), "Low", "BS, LV, Heston",
    ])

    tex = _latex_table(
        "tab:complexity",
        ["Method", "Parameters", "Epoch time", "Inference", "Memory", "Models"],
        rows,
    )
    (output_dir / "table7_1.tex").write_text(tex, encoding="utf-8")
    print("  -> table7_1.tex")


def main():
    parser = argparse.ArgumentParser(description="Generate all thesis tables")
    parser.add_argument("--results-file", type=str, default=None)
    args = parser.parse_args()

    print("=" * 60)
    print("GENERATING ALL THESIS TABLES")
    print("=" * 60)

    if args.results_file:
        results_file = Path(args.results_file)
    else:
        try:
            results_file = find_latest_results()
        except FileNotFoundError:
            print("WARNING: No results file found.")
            results_file = None

    if results_file and results_file.exists():
        print(f"\nLoading: {results_file}")
        with open(results_file, "r") as f:
            data = json.load(f)
    else:
        print("\nNo results file found. Tables will show '---' for missing data.")
        data = {}

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    generate_bs_table(data, OUTPUT_DIR)
    generate_lv_table(data, OUTPUT_DIR)
    generate_heston_table(data, OUTPUT_DIR)
    generate_ablation_table(data, OUTPUT_DIR)
    generate_complexity_table(data, OUTPUT_DIR)

    print("\n" + "=" * 60)
    print("DONE! Generated tables in:", OUTPUT_DIR)
    print("=" * 60)


if __name__ == "__main__":
    main()
