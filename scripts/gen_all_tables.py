NA = "---"


def find_latest_results() -> Path:
    # Timestamped files only: all_results_rolling.json sorts after any
    # all_results_<YYYYMMDD_HHMMSS>.json name and is a mid-run snapshot.
    results_files = sorted(RESULTS_DIR.glob("all_results_[0-9]*.json"), reverse=True)
    if not results_files:
        raise FileNotFoundError(f"No results files found in {RESULTS_DIR}")
    return results_files[0]


def fmt(mean: float | None, std: float | None, scale: float = 1.0, decimals: int = 2) -> str:
    """mean +/- std; values that would round to zero are shown in scientific notation."""
    if mean is None:
        return NA
    m = mean * scale
    s = (std if std is not None else 0.0) * scale
    if m != 0.0 and abs(m) < 0.5 * 10.0 ** (-decimals):
        e = math.floor(math.log10(abs(m)))
        return f"$({m / 10.0**e:.1f} \\pm {s / 10.0**e:.1f}) \\times 10^{{{e}}}$"
    return f"${m:.{decimals}f} \\pm {s:.{decimals}f}$"


def _get(data: dict, key: str, metric: str, kind: str = "mean") -> float | None:
    r = data.get(key, {})
    return r.get(kind, {}).get(metric)


def _row(data: dict, key: str, label: str, metrics: list[tuple[str, float, int]]) -> list[str]:
    """Build a table row. metrics is [(metric_name, scale, decimals), ...]."""
    cells = [label]
    for metric, scale, dec in metrics:
        m = _get(data, key, metric, "mean")
        s = _get(data, key, metric, "std")
        cells.append(fmt(m, s, scale=scale, decimals=dec))
    return cells


def _latex_table(caption_label: str, columns: list[str], rows: list[list[str]]) -> str:
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M")
    ncols = len(columns)
    col_spec = "l" + "c" * (ncols - 1)
    header = " & ".join(columns)
    lines = [
        f"% AUTO-GENERATED by gen_all_tables.py on {timestamp}",
        f"\\begin{{tabular}}{{{col_spec}}}",
        "  \\toprule",
        f"  {header} \\\\",
        "  \\midrule",
    ]
    for row in rows:
        lines.append("  " + " & ".join(row) + " \\\\")
    lines += ["  \\bottomrule", "\\end{tabular}", ""]
    return "\n".join(lines)


